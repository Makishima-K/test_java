package sef.module2.activity;

public class OperatorActivity {

    public static void main(String[] args) {
        // Given integers
        int a = 15;
        int b = 27;
        int c = 8;

        // Find the sum of the given integers
        int sum = a + b + c;

        // Print the result
        System.out.println("Sum of " + a + ", " + b + " and " + c + " = " + sum);
    }
}
