package sef.module2.activity;

public class VariableAssignmentActivity {

    public static void main(String[] args) {
        // 1. Declare a variable of type int and assign it the default value (0)
        int number = 0;
        System.out.println("Default value: " + number);

        // 2. Update the value
        number = 42;

        // 3. Print the updated value to the console
        System.out.println("Updated value: " + number);
    }
}
